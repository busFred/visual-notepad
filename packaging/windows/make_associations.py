#!/usr/bin/env python3
"""Writes associations.iss, the file types the Windows installer offers.

Run after changing TYPES:  python3 packaging/windows/make_associations.py

Each type the user ticks on the installer's "Select Additional Tasks" page
(grouped like K-Lite's codec pack: a group ticks or clears its types) gets
what Windows documents for "Open with" without taking over the default,
which since Windows 10 only the user sets (Windows asks the first time a
file is opened after a new app can open it):
  - a ProgID, VisualNotepad.<ext>, with its own open command;
  - that ProgID in .<ext>\\OpenWithProgids (Windows' suggested apps);
  - .<ext> in Applications\\visnotepad.exe\\SupportedTypes;
  - .<ext> in the app's Capabilities\\FileAssociations, which Settings >
    Default apps lists under Visual Notepad.
A type left unticked has all of it removed again (an earlier install may
have added it). See
https://learn.microsoft.com/windows/win32/shell/how-to-include-an-application-on-the-open-with-dialog-box
https://learn.microsoft.com/windows/win32/shell/app-registration
https://learn.microsoft.com/windows/win32/shell/default-programs
"""

import os

# (task name, group label, ticked at first, [(extension, file type name)])
TYPES = [
    ("markdown", "Markdown", True, [
        ("md", "Markdown document"), ("markdown", "Markdown document"),
        ("mdown", "Markdown document"), ("mkd", "Markdown document"),
        ("mkdn", "Markdown document"),
    ]),
    ("text", "Plain text", True, [
        ("txt", "Text document"), ("text", "Text document"), ("log", "Log file"),
    ]),
    ("config", "Configuration and data", False, [
        ("ini", "Configuration file"), ("cfg", "Configuration file"), ("conf", "Configuration file"),
        ("json", "JSON file"), ("jsonc", "JSON file"), ("yaml", "YAML file"), ("yml", "YAML file"),
        ("toml", "TOML file"), ("xml", "XML file"), ("csv", "CSV file"), ("tsv", "TSV file"),
        ("properties", "Properties file"), ("gitignore", "Git ignore file"),
        ("gitattributes", "Git attributes file"), ("editorconfig", "EditorConfig file"),
    ]),
    ("c", "C and C++", False, [
        ("c", "C source file"), ("h", "C header file"), ("cpp", "C++ source file"),
        ("cc", "C++ source file"), ("cxx", "C++ source file"), ("hpp", "C++ header file"),
        ("hh", "C++ header file"), ("hxx", "C++ header file"), ("cmake", "CMake file"),
    ]),
    ("python", "Python", False, [
        ("py", "Python file"), ("pyw", "Python file"), ("pyi", "Python stub file"),
    ]),
    ("web", "Web", False, [
        ("html", "HTML document"), ("htm", "HTML document"), ("css", "CSS file"),
        ("scss", "SCSS file"), ("js", "JavaScript file"), ("mjs", "JavaScript file"),
        ("cjs", "JavaScript file"), ("ts", "TypeScript file"), ("tsx", "TypeScript file"),
        ("jsx", "JavaScript file"),
    ]),
    ("other", "Other languages", False, [
        ("rs", "Rust file"), ("go", "Go file"), ("java", "Java file"), ("kt", "Kotlin file"),
        ("cs", "C# file"), ("rb", "Ruby file"), ("php", "PHP file"), ("lua", "Lua file"),
        ("swift", "Swift file"), ("sql", "SQL file"), ("r", "R file"), ("tex", "TeX document"),
        ("bib", "BibTeX file"),
    ]),
    ("scripts", "Shell scripts (only offered: double-clicking still runs them)", False, [
        ("sh", "Shell script"), ("bash", "Shell script"), ("zsh", "Shell script"),
        ("ps1", "PowerShell script"), ("psm1", "PowerShell module"), ("bat", "Batch file"),
        ("cmd", "Command script"), ("diff", "Diff file"), ("patch", "Patch file"),
    ]),
]

CLASSES = r"Software\Classes"
APP = r"Software\Classes\Applications\visnotepad.exe"
CAPABILITIES = r"Software\Visual Notepad\Capabilities"


def main():
    out = [
        "; Generated by make_associations.py: edit TYPES there, then run it.",
        "",
        "[Tasks]",
        # The tree: all types, a group, a type. A task ticks its own; a group
        # with none ticked clears itself (Inno's [Tasks] levels).
        'Name: "assoc"; Description: "Offer Visual Notepad to open these file types"; '
        'GroupDescription: "File types (Windows still asks before it changes a default):"',
    ]
    for task, label, ticked, types in TYPES:
        flags = "" if ticked else "; Flags: unchecked"
        out.append(f'Name: "assoc\\{task}"; Description: "{label}"{flags}')
        for ext, _ in types:
            out.append(f'Name: "assoc\\{task}\\{ext}"; Description: ".{ext}"{flags}')
    out += ["", "[Registry]"]
    for task, _, _, types in TYPES:
        for ext, name in types:
            t = f"assoc\\{task}\\{ext}"
            prog = f"VisualNotepad.{ext}"
            on = f"Tasks: {t}"
            off = f"Check: not WizardIsTaskSelected('{t}')"
            out += [
                f'; .{ext}',
                f'Root: HKA; Subkey: "{CLASSES}\\{prog}"; ValueType: string; ValueName: ""; '
                f'ValueData: "{name}"; Flags: uninsdeletekey; {on}',
                f'Root: HKA; Subkey: "{CLASSES}\\{prog}\\DefaultIcon"; ValueType: string; ValueName: ""; '
                f'ValueData: "{{app}}\\visnotepad.exe,0"; {on}',
                f'Root: HKA; Subkey: "{CLASSES}\\{prog}\\shell\\open\\command"; ValueType: string; ValueName: ""; '
                f'ValueData: """{{app}}\\visnotepad.exe"" ""%1"""; {on}',
                # Keys Windows had none of go again on uninstall when empty.
                f'Root: HKA; Subkey: "{CLASSES}\\.{ext}"; Flags: uninsdeletekeyifempty; {on}',
                f'Root: HKA; Subkey: "{CLASSES}\\.{ext}\\OpenWithProgids"; ValueType: string; ValueName: "{prog}"; '
                f'ValueData: ""; Flags: uninsdeletevalue uninsdeletekeyifempty; {on}',
                f'Root: HKA; Subkey: "{APP}\\SupportedTypes"; ValueType: string; ValueName: ".{ext}"; '
                f'ValueData: ""; {on}',
                f'Root: HKA; Subkey: "{CAPABILITIES}\\FileAssociations"; ValueType: string; ValueName: ".{ext}"; '
                f'ValueData: "{prog}"; {on}',
                # Left unticked: whatever an earlier install added goes
                # (dontcreatekey: no empty key is made where there was none).
                f'Root: HKA; Subkey: "{CLASSES}\\{prog}"; ValueType: none; Flags: deletekey dontcreatekey; {off}',
                f'Root: HKA; Subkey: "{CLASSES}\\.{ext}\\OpenWithProgids"; ValueType: none; ValueName: "{prog}"; '
                f'Flags: deletevalue dontcreatekey; {off}',
                f'Root: HKA; Subkey: "{APP}\\SupportedTypes"; ValueType: none; ValueName: ".{ext}"; '
                f'Flags: deletevalue dontcreatekey; {off}',
                f'Root: HKA; Subkey: "{CAPABILITIES}\\FileAssociations"; ValueType: none; ValueName: ".{ext}"; '
                f'Flags: deletevalue dontcreatekey; {off}',
            ]
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "associations.iss")
    with open(path, "w", encoding="utf-8", newline="\r\n") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", path, sum(len(t[3]) for t in TYPES), "types")


if __name__ == "__main__":
    main()
